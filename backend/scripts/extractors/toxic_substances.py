class ToxicSubstancesExtractor(BaseExtractor):
    """Extract toxic substances from pages 230-245."""

    def extract(self) -> dict:
        print("\n=== Extracting Toxic Substances (pages 230-245) ===")

        records = []
        for name_rus, name_eng, category, description, source_page in TOXIC_SUBSTANCES_DATA:
            records.append({
                "name_rus": name_rus,
                "name_eng": name_eng,
                "category": category,
                "description": description,
                "source_page": source_page,
            })

        # Category stats
        cat_counts: dict[str, int] = {}
        for r in records:
            cat_counts[r["category"]] = cat_counts.get(r["category"], 0) + 1
        for cat, cnt in sorted(cat_counts.items()):
            print(f"  {cat}: {cnt}")

        print(f"  Total: {len(records)} substances")

        self.save_debug("toxic_substances", records)

        conn = self.get_db_connection()
        for rec in records:
            conn.execute(
                "INSERT INTO toxic_substances "
                "(name_rus, name_eng, category, description, source_page) "
                "VALUES (?, ?, ?, ?, ?)",
                (rec["name_rus"], rec["name_eng"], rec["category"],
                 rec["description"], rec["source_page"]),
            )
        conn.commit()

        print(f"  Inserted {len(records)} records into toxic_substances")
        self.preview(conn, "toxic_substances", 5)
        conn.close()

        return {"records": len(records)}

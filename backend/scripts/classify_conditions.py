def main():
    if not DB_PATH.exists():
        print(f"ERROR: Database not found at {DB_PATH}")
        sys.exit(1)

    db = sqlite3.connect(str(DB_PATH))
    db.row_factory = sqlite3.Row

    # Ensure column exists
    try:
        db.execute("ALTER TABLE therapeutic_index ADD COLUMN disease_system TEXT")
        db.commit()
    except Exception:
        pass

    # Get total conditions count
    total = db.execute("SELECT COUNT(*) as cnt FROM therapeutic_index").fetchone()["cnt"]
    print(f"Total conditions in DB: {total}")
    print(f"Conditions to classify: {len(CLASSIFICATION)}")

    # Apply classification
    updated = 0
    for cond_id, disease_system in CLASSIFICATION.items():
        cursor = db.execute(
            "UPDATE therapeutic_index SET disease_system = ? WHERE id = ?",
            (disease_system, cond_id),
        )
        if cursor.rowcount > 0:
            updated += 1
        else:
            print(f"  WARNING: condition id={cond_id} not found in DB")

    db.commit()

    # Stats
    classified = db.execute(
        "SELECT COUNT(*) as cnt FROM therapeutic_index WHERE disease_system IS NOT NULL"
    ).fetchone()["cnt"]
    unclassified = db.execute(
        "SELECT COUNT(*) as cnt FROM therapeutic_index WHERE disease_system IS NULL"
    ).fetchone()["cnt"]

    print(f"\nResult:")
    print(f"  Updated: {updated}")
    print(f"  Classified: {classified}/{total} ({classified*100//total}%)")
    print(f"  Unclassified (NULL): {unclassified}")

    # Show distribution
    print("\nDistribution by disease_system:")
    rows = db.execute(
        "SELECT disease_system, COUNT(*) as cnt "
        "FROM therapeutic_index WHERE disease_system IS NOT NULL "
        "GROUP BY disease_system ORDER BY cnt DESC"
    ).fetchall()
    for r in rows:
        print(f"  {r['cnt']:3d} | {r['disease_system']}")

    # Show unclassified
    if unclassified > 0:
        print(f"\nUnclassified conditions ({unclassified}):")
        rows = db.execute(
            "SELECT id, condition_name FROM therapeutic_index "
            "WHERE disease_system IS NULL ORDER BY condition_name"
        ).fetchall()
        for r in rows:
            print(f"  {r['id']:3d} | {r['condition_name']}")

    db.close()
    print("\nDone.")


if __name__ == "__main__":
    main()
